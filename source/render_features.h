#ifndef NANOVA_RENDER_FEATURES_H
#define NANOVA_RENDER_FEATURES_H

// F5 through F9 use these bits in key order.
enum RenderFeature {
    RENDER_SSS=1u<<0, RENDER_VOLUME=1u<<1, RENDER_CELL_BLUR=1u<<2,
    RENDER_TILT_SHIFT=1u<<3, RENDER_FOG_BLUR=1u<<4,
    RENDER_FEATURE_MASK=RENDER_SSS|RENDER_VOLUME|RENDER_CELL_BLUR|RENDER_TILT_SHIFT|RENDER_FOG_BLUR
};

#endif
